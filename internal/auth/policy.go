// Password and user name rules (NIST SP 800-63B, PHASE1 step 10): length
// instead of composition rules, no expiry, a check against common passwords.
const (
	MinPasswordRunes = 12
	MaxPasswordRunes = 256
	MaxUsername      = 64
)

// ErrWeakPassword is wrapped by every *PolicyError.
var ErrWeakPassword = errors.New("password refused")

// PolicyError lists every rule a password breaks.
type PolicyError struct{ Reasons []string }

func (e *PolicyError) Error() string { return "password refused: " + strings.Join(e.Reasons, "; ") }

func (e *PolicyError) Unwrap() error { return ErrWeakPassword }

// ErrBadUsername: user names are refused, never converted.
var ErrBadUsername = errors.New("user name: 1 to 64 characters, lower case a-z, digits and . _ @ -, starting with a letter or digit")

// CheckUsername applies the user name rule. Upper case is refused, not
// lowered: the name a user types is the name that is stored.
func CheckUsername(name string) error {
	if name == "" || len(name) > MaxUsername {
		return ErrBadUsername
	}
	for i, c := range name {
		switch {
		case c >= 'a' && c <= 'z', c >= '0' && c <= '9':
		case i > 0 && strings.ContainsRune("._@-", c):
		default:
			return ErrBadUsername
		}
	}
	return nil
}

// CheckPassword applies the password rules for username.
func CheckPassword(username, password string) error {
	var reasons []string
	n := utf8.RuneCountInString(password)
	switch {
	case !utf8.ValidString(password):
		reasons = append(reasons, "not valid UTF-8")
	case n < MinPasswordRunes:
		reasons = append(reasons, fmt.Sprintf("at least %d characters (a passphrase of a few words is easy to type and hard to guess)", MinPasswordRunes))
	case n > MaxPasswordRunes:
		reasons = append(reasons, fmt.Sprintf("at most %d characters", MaxPasswordRunes))
	}
	if strings.ContainsFunc(password, unicode.IsControl) {
		reasons = append(reasons, "no control characters")
	}
	lower := strings.ToLower(password)
	if len(username) >= 3 && strings.Contains(lower, strings.ToLower(username)) {
		reasons = append(reasons, "must not contain the user name")
	}
	if strings.Contains(lower, "myownpki") {
		reasons = append(reasons, "must not contain the product name")
	}
	if n >= MinPasswordRunes && monotonous(password) {
		reasons = append(reasons, "one repeated character or a plain sequence like abcdef… is not a password")
	}
	if isCommonPassword(lower) {
		reasons = append(reasons, "this is a well-known password from leaked password lists")
	}
	if len(reasons) > 0 {
		return &PolicyError{Reasons: reasons}
	}
	return nil
}

// monotonous: every character equals, or is one above or one below, the one
// before (aaaa…, abcd…, 4321…).
func monotonous(s string) bool {
	rs := []rune(s)
	for _, step := range []rune{0, 1, -1} {
		ok := true
		for i := 1; i < len(rs) && ok; i++ {
			ok = rs[i]-rs[i-1] == step
		}
		if ok {
			return true
		}
	}
	return false
}

// commonPasswordsFile: generated by internal/tools/commonpasswords, origin
// and license in THIRD_PARTY.md.
//
//go:embed common-passwords.txt
var commonPasswordsFile string

var commonPasswords = sync.OnceValue(func() map[string]struct{} {
	set := make(map[string]struct{}, 50000)
	for line := range strings.SplitSeq(commonPasswordsFile, "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		set[line] = struct{}{}
	}
	return set
})

// isCommonPassword reports lower in the list (which is lower case).
func isCommonPassword(lower string) bool {
	_, ok := commonPasswords()[lower]
	return ok
}

func validUsername(name string) bool { return CheckUsername(name) == nil }
