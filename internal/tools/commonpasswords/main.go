// Command commonpasswords builds internal/auth/common-passwords.txt, the list
// of common passwords that new passwords are checked against (NIST SP 800-63B,
// PHASE1 step 10). Origin and license: THIRD_PARTY.md.
//
// It reads the top one million of Mark Burnett's ten million passwords as
// published in SecLists, checks the file against a pinned SHA-256, and keeps
// what the password policy could still accept: 12 to 256 characters. Entries
// are lower-cased (the check ignores case), deduplicated and sorted, so the
// output is the same on every machine.
//
// Usage:
//
//	curl -o xato.txt <Source>
//	go run ./internal/tools/commonpasswords -in xato.txt -out internal/auth/common-passwords.txt
package main

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"
)

// Source is the input, pinned to a SecLists commit.
const Source = "https://raw.githubusercontent.com/danielmiessler/SecLists/f1196104c5594a19d78b486c52c0794b9d947993/Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt"

// SourceSHA256 pins the content of Source.
const SourceSHA256 = "424a3e03a17df0a2bc2b3ca749d81b04e79d59cb7aeec8876a5a3f308d0caf51"

// The password policy's length limits (internal/auth): shorter or longer
// entries are refused by the length rule already.
const minRunes, maxRunes = 12, 256

func main() {
	in := flag.String("in", "", "the downloaded source file")
	out := flag.String("out", "internal/auth/common-passwords.txt", "the list to write")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "commonpasswords:", err)
		os.Exit(1)
	}
}

func run(inPath, outPath string) error {
	if inPath == "" {
		return errors.New("-in is required (download " + Source + ")")
	}
	data, err := os.ReadFile(inPath)
	if err != nil {
		return err
	}
	if sum := sha256.Sum256(data); hex.EncodeToString(sum[:]) != SourceSHA256 {
		return fmt.Errorf("%s: SHA-256 %x, want %s – not the pinned source file", inPath, sum, SourceSHA256)
	}
	list := filter(strings.NewReader(string(data)))
	f, err := os.Create(outPath)
	if err != nil {
		return err
	}
	w := bufio.NewWriter(f)
	_, _ = fmt.Fprintf(w, "# Common passwords with %d to %d characters, lower case, sorted.\n", minRunes, maxRunes)
	_, _ = fmt.Fprintf(w, "# Generated by internal/tools/commonpasswords – do not edit. Origin and license: THIRD_PARTY.md.\n")
	_, _ = fmt.Fprintf(w, "# Source: %s\n# SHA-256: %s\n", Source, SourceSHA256)
	for _, p := range list {
		_, _ = fmt.Fprintln(w, p)
	}
	if err := w.Flush(); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	_, _ = fmt.Fprintf(os.Stdout, "%s: %d entries\n", outPath, len(list))
	return nil
}

// filter keeps entries the policy could accept, lower-cased, without
// duplicates and in byte order. Lines with invalid UTF-8, control characters
// or a leading '#' (the comment marker of the output) are dropped.
func filter(r io.Reader) []string {
	seen := map[string]bool{}
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := strings.TrimRight(sc.Text(), "\r")
		n := utf8.RuneCountInString(line)
		if n < minRunes || n > maxRunes || !utf8.ValidString(line) || strings.HasPrefix(line, "#") ||
			strings.ContainsFunc(line, unicode.IsControl) {
			continue
		}
		seen[strings.ToLower(line)] = true
	}
	list := make([]string, 0, len(seen))
	for p := range seen {
		list = append(list, p)
	}
	slices.Sort(list)
	return list
}
